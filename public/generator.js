function formatDate(value) {
  if(!value) return '협의 필요';
  const [y,m,d]=value.split('-').map(Number);
  const date=new Date(y,m-1,d);
  return `${y}년 ${m}월 ${d}일(${['일','월','화','수','목','금','토'][date.getDay()]})`;
}
